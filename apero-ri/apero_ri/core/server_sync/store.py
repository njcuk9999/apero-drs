# Define peer functions (servers we sync with)
# =============================================================================
def _peers_path() -> Path:
    return sync_dir() / 'peers.yaml'


def _peer_tokens_path() -> Path:
    return secret_dir() / 'peer_tokens.json'


def load_peers() -> Dict[str, Dict[str, Any]]:
    """
    Load configured peers (no secrets).

    :return: dict peer_id -> peer config
    :rtype: dict
    """
    path = _peers_path()
    if not path.exists():
        return dict()
    with open(path, 'r', encoding='utf-8') as fio:
        data = yaml.safe_load(fio) or dict()
    return dict(data.get('peers') or dict())


def save_peers(peers: Dict[str, Dict[str, Any]]) -> None:
    """
    Persist the peer configuration.

    :param peers: dict peer_id -> peer config

    :return: None
    """
    payload = dict(peers=peers)
    write_atomic(_peers_path(), yaml.safe_dump(payload, sort_keys=False))


def get_peer(peer_id: str) -> Optional[Dict[str, Any]]:
    """
    Return one peer config.

    :param peer_id: str, local peer id

    :return: dict or None
    :rtype: dict
    """
    return load_peers().get(str(peer_id or ''))


def update_peer(peer_id: str, **changes: Any) -> Dict[str, Any]:
    """
    Update fields on an existing peer.

    :param peer_id: str, local peer id
    :param changes: fields to set

    :return: dict, updated peer config
    :rtype: dict
    :raises KeyError: if the peer does not exist
    """
    peers = load_peers()
    if peer_id not in peers:
        raise KeyError(peer_id)
    peers[peer_id].update(changes)
    peers[peer_id]['updated_at'] = now_iso()
    save_peers(peers)
    return peers[peer_id]


def add_peer(peer: Dict[str, Any], token: str) -> Dict[str, Any]:
    """
    Add a peer and store its token secret.

    :param peer: dict, peer config (peer_id assigned here)
    :param token: str, pairing token issued by the peer

    :return: dict, stored peer config
    :rtype: dict
    """
    key_id, _ = crypto.parse_token(token)
    peers = load_peers()
    peer_id = uuid.uuid4().hex
    peer['peer_id'] = peer_id
    peer['key_id'] = key_id
    peer['created_at'] = now_iso()
    peer['updated_at'] = peer['created_at']
    peers[peer_id] = peer
    set_peer_token(peer_id, token)
    save_peers(peers)
    return peer


def set_peer_token(peer_id: str, token: str) -> None:
    """
    Store (or replace) the token used to reach a peer.

    :param peer_id: str, local peer id
    :param token: str, pairing token

    :return: None
    """
    crypto.parse_token(token)
    tokens = read_json(_peer_tokens_path(), dict())
    tokens[peer_id] = str(token).strip()
    write_json(_peer_tokens_path(), tokens, mode=0o600)


def get_peer_token(peer_id: str) -> str:
    """
    Return the stored token for a peer.

    :param peer_id: str, local peer id

    :return: str, pairing token ('' if missing)
    :rtype: str
    """
    return str(read_json(_peer_tokens_path(), dict()).get(peer_id) or '')


def delete_peer(peer_id: str) -> bool:
    """
    Remove a peer, its token and all of its sync state.

    :param peer_id: str, local peer id

    :return: bool, True if the peer existed
    :rtype: bool
    """
    peers = load_peers()
    existed = peers.pop(peer_id, None) is not None
    save_peers(peers)
    tokens = read_json(_peer_tokens_path(), dict())
    if tokens.pop(peer_id, None) is not None:
        write_json(_peer_tokens_path(), tokens, mode=0o600)
    if existed:
        shutil.rmtree(peer_dir(peer_id), ignore_errors=True)
    return existed


