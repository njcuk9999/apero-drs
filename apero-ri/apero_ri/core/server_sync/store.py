# Define file helpers
# =============================================================================
def read_json(path: Path, default: Any) -> Any:
    """
    Load a JSON file, returning a default when absent or unreadable.

    :param path: Path, file to read
    :param default: Any, value returned when the file is unusable

    :return: Any, decoded JSON
    :rtype: Any
    """
    if not path.exists():
        return default
    try:
        with open(path, 'r', encoding='utf-8') as fio:
            return json.load(fio)
    except (OSError, ValueError):
        return default


def write_atomic(path: Path, text: str, mode: Optional[int] = None) -> None:
    """
    Write text to a file atomically (temp file + rename).

    :param path: Path, destination file
    :param text: str, file contents
    :param mode: int or None, chmod applied before the rename

    :return: None
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=f'.{path.name}.')
    try:
        with os.fdopen(fd, 'w', encoding='utf-8') as fio:
            fio.write(text)
        if mode is not None:
            os.chmod(tmp, mode)
        os.replace(tmp, path)
    finally:
        if os.path.exists(tmp):
            os.unlink(tmp)


def write_json(path: Path, data: Any, mode: Optional[int] = None) -> None:
    """
    Write JSON atomically.

    :param path: Path, destination file
    :param data: Any, JSON-serialisable data
    :param mode: int or None, optional file mode

    :return: None
    """
    write_atomic(path, json.dumps(data, indent=1, default=str), mode)


@contextlib.contextmanager
def sync_lock(blocking: bool = False) -> Iterator[None]:
    """
    Hold the process-wide sync lock (one sync run per server at a time).

    :param blocking: bool, wait for the lock instead of failing

    :return: context manager
    :raises SyncBusy: if the lock is held and blocking is False
    """
    with open(sync_dir() / 'sync.lock', 'a', encoding='utf-8') as lock:
        flags = fcntl.LOCK_EX if blocking else fcntl.LOCK_EX | fcntl.LOCK_NB
        try:
            fcntl.flock(lock, flags)
        except BlockingIOError as exc:
            raise SyncBusy('Another server sync is already running') from exc
        try:
            yield
        finally:
            fcntl.flock(lock, fcntl.LOCK_UN)


@contextlib.contextmanager
def journal_lock() -> Iterator[None]:
    """
    Serialise short journal/apply operations (blocking).

    Separate from sync_lock so a peer can still read our manifest or
    push records while this server runs its own sync.

    :return: context manager
    """
    with open(sync_dir() / 'journal.lock', 'a', encoding='utf-8') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        try:
            yield
        finally:
            fcntl.flock(lock, fcntl.LOCK_UN)


