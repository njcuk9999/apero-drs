# Define issued-token functions (tokens other servers use to reach us)
# =============================================================================
def _issued_path() -> Path:
    return secret_dir() / 'issued_tokens.json'


def list_issued() -> List[Dict[str, Any]]:
    """
    List issued tokens without their secrets.

    :return: list of token metadata dicts
    :rtype: list
    """
    tokens = read_json(_issued_path(), dict())
    rows = []
    for key_id, info in tokens.items():
        row = {k: v for k, v in info.items() if k != 'secret'}
        row['key_id'] = key_id
        rows.append(row)
    return sorted(rows, key=lambda r: str(r.get('created_at', '')))


def issue_token(label: str, scope: str, created_by: str) -> str:
    """
    Create a token another server can use to sync with this one.

    :param label: str, free text describing the other server
    :param scope: str, 'read' (copy from us) or 'readwrite' (mirror)
    :param created_by: str, admin username

    :return: str, the full token (shown once)
    :rtype: str
    :raises ValueError: for an unknown scope
    """
    if scope not in SCOPES:
        raise ValueError(f'Scope must be one of {SCOPES}')
    key_id, secret, token = crypto.new_token()
    tokens = read_json(_issued_path(), dict())
    entry = dict()
    entry['secret'] = secret
    entry['label'] = str(label or '').strip()[:120]
    entry['scope'] = scope
    entry['created_at'] = now_iso()
    entry['created_by'] = created_by
    entry['last_used_at'] = None
    entry['last_used_by'] = None
    tokens[key_id] = entry
    write_json(_issued_path(), tokens, mode=0o600)
    return token


def revoke_issued(key_id: str) -> bool:
    """
    Revoke an issued token.

    :param key_id: str, token key id

    :return: bool, True if a token was removed
    :rtype: bool
    """
    tokens = read_json(_issued_path(), dict())
    if tokens.pop(key_id, None) is None:
        return False
    write_json(_issued_path(), tokens, mode=0o600)
    return True


def get_issued(key_id: str) -> Optional[Dict[str, Any]]:
    """
    Return an issued token entry including its secret.

    :param key_id: str, token key id

    :return: dict or None
    :rtype: dict
    """
    return read_json(_issued_path(), dict()).get(str(key_id or ''))


def touch_issued(key_id: str, server_label: str) -> None:
    """
    Record the last use of an issued token.

    :param key_id: str, token key id
    :param server_label: str, name/id of the calling server

    :return: None
    """
    tokens = read_json(_issued_path(), dict())
    if key_id not in tokens:
        return
    # only rewrite occasionally to keep request handling cheap
    last = tokens[key_id].get('last_used_ts') or 0
    if time.time() - float(last) < 60:
        return
    tokens[key_id]['last_used_at'] = now_iso()
    tokens[key_id]['last_used_ts'] = time.time()
    tokens[key_id]['last_used_by'] = str(server_label or '')[:120]
    write_json(_issued_path(), tokens, mode=0o600)


def check_nonce(key_id: str, nonce: str) -> bool:
    """
    Record a nonce, returning False if it was already used.

    :param key_id: str, token key id
    :param nonce: str, request nonce

    :return: bool, True when the nonce is fresh
    :rtype: bool
    """
    # sqlite gives cross-process uniqueness (multiple Flask workers)
    con = sqlite3.connect(str(sync_dir() / 'nonces.db'), timeout=10)
    try:
        con.execute('CREATE TABLE IF NOT EXISTS nonces (key TEXT PRIMARY KEY,'
                    ' ts REAL NOT NULL)')
        now = time.time()
        con.execute('DELETE FROM nonces WHERE ts < ?', (now - NONCE_TTL,))
        try:
            con.execute('INSERT INTO nonces (key, ts) VALUES (?, ?)',
                        (f'{key_id}:{nonce}', now))
        except sqlite3.IntegrityError:
            return False
        con.commit()
        return True
    finally:
        con.close()


