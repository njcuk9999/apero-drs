__NAME__ = 'apero_ri.core.server_sync.store'
# allowed scopes on an issued token
SCOPES = ('read', 'readwrite')
# allowed sync modes for a peer
MODES = ('mirror', 'copy')
# how long a nonce is remembered (must exceed the allowed clock window)
NONCE_TTL = 900.0
# maximum number of history lines returned to the UI
HISTORY_LIMIT = 500


class SyncBusy(RuntimeError):
    """Raised when another sync already holds the sync lock."""


# =============================================================================
# Define path helpers
# =============================================================================
def now_iso() -> str:
    """
    Return the current UTC time as an ISO string.

    :return: str, ISO 8601 timestamp
    :rtype: str
    """
    return datetime.now(timezone.utc).isoformat(timespec='seconds')


def sync_dir() -> Path:
    """
    Return (and create) the admin/server_sync directory.

    :return: Path to the sync state directory
    :rtype: Path
    """
    path = Path(auth.ARI_DIR) / 'admin' / 'server_sync'
    path.mkdir(parents=True, exist_ok=True)
    return path


def secret_dir() -> Path:
    """
    Return (and create) the secret/server_sync directory (mode 0700).

    :return: Path to the secret directory
    :rtype: Path
    """
    path = Path(auth.ARI_DIR) / 'secret' / 'server_sync'
    path.mkdir(parents=True, exist_ok=True)
    secret_store.protect_path(path.parent, 0o700)
    secret_store.protect_path(path, 0o700)
    return path


def peer_dir(peer_id: str) -> Path:
    """
    Return (and create) the state directory for one peer.

    :param peer_id: str, local peer id (uuid hex)

    :return: Path to the peer state directory
    :rtype: Path
    :raises ValueError: if the peer id is not a plain hex id
    """
    # peer ids are generated by us; refuse anything that could escape
    if not peer_id or not all(c in '0123456789abcdef' for c in peer_id):
        raise ValueError('Invalid peer id')
    path = sync_dir() / 'peers' / peer_id
    path.mkdir(parents=True, exist_ok=True)
    return path


