def get_identity() -> Dict[str, str]:
    """
    Return this server's sync identity, creating it on first use.

    :return: dict with server_id, server_name and created_at
    :rtype: dict
    """
    path = sync_dir() / 'identity.yaml'
    data = dict()
    if path.exists():
        with open(path, 'r', encoding='utf-8') as fio:
            data = yaml.safe_load(fio) or dict()
    if not data.get('server_id'):
        data['server_id'] = uuid.uuid4().hex
        data['server_name'] = socket.gethostname()
        data['created_at'] = now_iso()
        write_atomic(path, yaml.safe_dump(data, sort_keys=False))
    return data


def set_server_name(name: str) -> Dict[str, str]:
    """
    Update the human-readable name of this server.

    :param name: str, new display name

    :return: dict, the updated identity
    :rtype: dict
    """
    data = get_identity()
    data['server_name'] = str(name or '').strip()[:80] or data['server_name']
    write_atomic(sync_dir() / 'identity.yaml',
                 yaml.safe_dump(data, sort_keys=False))
    return data


def root_username() -> str:
    """
    Return the setup ("root") admin username that is never synced.

    :return: str, username or '' when setup state has none
    :rtype: str
    """
    state = bootstrap.load_setup_state(Path(auth.ARI_DIR))
    return str(state.get('admin_username') or '').strip()


